"""Утилиты для маскировки чувствительных данных в логах."""


def mask_phone(phone: str) -> str:
    """Маскирует номер телефона для безопасного логирования.
    
    Оставляет первые 4 символа и последние 2 символа,
    остальное заменяет на звездочки.
    
    Args:
        phone: Номер телефона для маскировки
        
    Returns:
        Замаскированный номер телефона
        
    Examples:
        >>> mask_phone("+79123456789")
        '+791***89'
        >>> mask_phone("123")
        '***'
    """
    if not phone:
        return "***"
    
    phone = str(phone).strip()
    
    if len(phone) < 8:
        return "***"
    
    # Оставляем первые 4 символа и последние 2
    return phone[:4] + "***" + phone[-2:]
